/**
 * Writes docs/VALIDATION.md: scientific validation tables of the eclipse engine.
 *
 *   npm run data:validate
 *
 * Note: imports src/lib/validation.ts, which reads src/data/*.json and public/data.
 */
import { writeFileSync } from 'node:fs';
import { crossComparison, nasaComparison } from '../src/lib/validation.ts';
import { ADOPTED_DELTA_T, eclipseAt } from '../src/lib/eclipse/index.ts';
import { cities } from '../src/lib/data.ts';

const f = (v: number | null, d = 1) => (v === null ? '—' : v.toFixed(d));
const mmss = (s: number | null) => (s === null ? '—' : `${Math.floor(Math.round(s) / 60)} min ${String(Math.round(s) % 60).padStart(2, '0')} s`);
const utc = (d?: Date) => (d ? d.toISOString().slice(11, 19) : '—');

const nasa = nasaComparison('08:40', '09:40');
const cross = crossComparison();
const maxDur = Math.max(...nasa.map((r) => Math.abs(r.engineDuration - r.nasaDuration)));
const maxKm = Math.max(...nasa.flatMap((r) => [Math.abs(r.northKm), Math.abs(r.southKm)]));

const lines: string[] = [];
lines.push('# Scientific validation of the eclipse engine', '');
lines.push(`Generated by \`npm run data:validate\` on ${new Date().toISOString().slice(0, 10)}. Engine: \`src/lib/eclipse/\`.`, '');
lines.push('## 1. Engine vs NASA path table (ΔT = 76.0 s, as NASA)', '');
lines.push(
  `Reference: NASA GSFC, *Path of the Total Solar Eclipse of 2027 Aug 02* (tests/fixtures/nasa-path-2027.json). For each row, the engine computes the central duration at NASA's central-line point and the latitude of each limit on NASA's meridian. **Max |Δ duration| = ${maxDur.toFixed(2)} s; max |Δ limit| = ${maxKm.toFixed(2)} km** (NASA coordinates are rounded to 0.1′ ≈ 0.18 km).`,
  '',
);
lines.push('| UT | Central line (lat, lon) | NASA duration (s) | Engine (s) | Δ (s) | Δ north limit (km) | Δ south limit (km) |');
lines.push('|---|---|---:|---:|---:|---:|---:|');
for (const r of nasa) {
  lines.push(`| ${r.ut} | ${r.lat.toFixed(3)}, ${r.lon.toFixed(3)} | ${r.nasaDuration.toFixed(1)} | ${r.engineDuration.toFixed(1)} | ${(r.engineDuration - r.nasaDuration).toFixed(2)} | ${r.northKm.toFixed(2)} | ${r.southKm.toFixed(2)} |`);
}
lines.push('', `## 2. Engine vs Astronomy Engine 2.1.19 (same ΔT = ${ADOPTED_DELTA_T} s)`, '');
lines.push('Differences engine − Astronomy Engine in seconds. "Limit" = distance to the nearest limit of totality along the meridian (negative = outside the path).', '');
lines.push('| Town | Engine | AE | Limit (km) | ΔC1 | ΔC2 | ΔMax | ΔC3 | ΔC4 | Totality engine | Totality AE |');
lines.push('|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|');
for (const r of cross) {
  lines.push(
    `| ${r.id} | ${r.kind} | ${r.refKind} | ${r.limitKm === null ? '—' : (r.inside ? '' : '−') + r.limitKm.toFixed(1)} | ${f(r.dC1)} | ${f(r.dC2)} | ${f(r.dMax)} | ${f(r.dC3)} | ${f(r.dC4)} | ${mmss(r.duration)} | ${mmss(r.refDuration)} |`,
  );
}
lines.push(
  '',
  'Interpretation: partial-phase contacts and maximum agree within ~2–3 s. Totality agrees on the northern side of the path; Astronomy Engine places the southern limit ~2–4 km further south (larger lunar radius plus small ephemeris differences), hence longer totality in the south and Kébili/Matmata classified as total by AE but partial by the NASA-based engine. Both lie within 5 km of the limit and are flagged by the site.',
  '',
);
lines.push('## 3. Published values (secondary source)', '');
lines.push('nationaleclipse.com, *2027 Total Solar Eclipse Overview* (method not documented), consulted 2026-10-25.', '');
lines.push('| Town | Published | Engine | Δ |', '|---|---:|---:|---:|');
for (const [id, label, pub] of [
  ['sfax', 'Sfax', 339],
  ['sidi-bouzid', 'Sidi Bouzid', 331],
  ['gafsa', 'Gafsa (≈)', 310],
  ['gabes', 'Gabès (≈)', 248],
  ['el-jem', 'El Jem', 265],
  ['kairouan', 'Kairouan (≈)', 165],
] as const) {
  const c = cities.find((x) => x.id === id)!;
  const e = eclipseAt(c.lat, c.lon);
  lines.push(`| ${label} | ${mmss(pub)} | ${mmss(e.centralDuration ?? null)} | ${Math.round((e.centralDuration ?? 0) - pub) || 0} s |`);
}
lines.push('', '## 4. Local circumstances of all towns (adopted ΔT, sea level)', '');
lines.push('| Town | Type | C1 (UTC) | C2 | Max | C3 | C4 | Duration | Magnitude | Obscuration |');
lines.push('|---|---|---|---|---|---|---|---:|---:|---:|');
for (const c of [...cities].sort((a, b) => b.lat - a.lat)) {
  const e = eclipseAt(c.lat, c.lon);
  lines.push(
    `| ${c.name.en} | ${e.kind} | ${utc(e.c1?.time)} | ${utc(e.c2?.time)} | ${utc(e.max?.time)} | ${utc(e.c3?.time)} | ${utc(e.c4?.time)} | ${mmss(e.centralDuration ?? null)} | ${e.max!.magnitude.toFixed(4)} | ${(e.max!.obscuration * 100).toFixed(3)} % |`,
  );
}
writeFileSync('docs/VALIDATION.md', `${lines.join('\n')}\n`);
console.log('Wrote docs/VALIDATION.md');
